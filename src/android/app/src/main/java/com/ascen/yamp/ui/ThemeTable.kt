    private val BY_NAME = THEMES.associateBy { it.name }

    /** 옛 이름 → 새 이름 ("light" = 이전 라이트 → 클린 블루). 모르는 이름은 그대로 (of() 가 기본으로) */
    fun normalize(name: String): String = if (name.trim() == "light") "clean_blue" else name.trim()

    /** 이름 → 테마 (옛 이름 처리, 모르면 기본 써니) */
    fun of(name: String): ThemeDef = BY_NAME[normalize(name)] ?: BY_NAME.getValue(DEFAULT)

    /**
     * 실제로 쓸 테마 (D3): 어두운 모드 따라가기가 켜져 있고 기기가 어두운 모드면
     *   밝은 테마 → 짝 테마 (써니 → 나이트 써니, 라이트 n단계 → 다크 n단계, 나머지 밝은 테마 → 다크 블루). 어두운 테마는 그대로
     */
    fun effective(name: String, followSystemDark: Boolean, systemDark: Boolean): String {
        val t = of(name)
        if (!followSystemDark || !systemDark || t.dark) return t.name
        return NIGHT[t.name] ?: "dark"
    }

    /** 어두운 모드 짝 (v024: 라이트 n단계 → 다크 n단계, 써니 → 나이트 써니, 나머지 밝은 테마 → 다크 블루) */
    val NIGHT: Map<String, String> = mapOf(DEFAULT to "night_sunny") + (1..5).associate { "light$it" to "dark$it" }

    /** D2 결과: theme = 저장할 이름, toast = 보여 줄 알림 (없으면 null) */
    data class Migration(val theme: String, val toast: String?)

    /**
     * D2 (이 버전 처음 실행 때 한 번): 저장된 테마가 이전 기본 'neon' 이면 'sunny' 로 + 알림.
     *   옛 'light' 는 언제나 'clean_blue'. migrated = 이미 한 번 했음 → neon 그대로 (사용자가 다시 고른 것)
     */
    fun migrate(stored: String, migrated: Boolean): Migration {
        val n = normalize(stored)
        if (!migrated && n == OLD_DEFAULT) return Migration(DEFAULT, MIGRATE_TOAST)
        return Migration(n, null)
    }

    /** "#RRGGBB" → ARGB Int (alpha 0..255) */
    fun argb(hex: String, alpha: Int = 255): Int {
        val h = hex.trim().removePrefix("#")
        require(h.length == 6) { "색 형식 오류: $hex" }
        return (alpha.coerceIn(0, 255) shl 24) or h.toInt(16)
    }
