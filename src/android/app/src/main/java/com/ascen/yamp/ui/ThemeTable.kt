/** 테마 하나: 이름(키) · 메뉴 이름 · 어두운 테마 여부 · 토큰 → "#RRGGBB" · EQ 막대 11색 (프리앰프 + 10밴드) */
data class ThemeDef(
    val name: String,
    val label: String,
    val dark: Boolean,
    val tokens: Map<String, String>,
    val bands: List<String>,
) {
    fun hex(token: String): String = tokens[token] ?: error("테마 $name: 토큰 없음 $token")
    fun argb(token: String, alpha: Int = 255): Int = ThemeTable.argb(hex(token), alpha)
}

